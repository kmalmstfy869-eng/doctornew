<?php

namespace App\Http\Requests\Doctor;

use App\Models\Patient;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Validator;

class VisitRequest extends FormRequest
{
    /**
     * bag مخصص لفورم الزيارة عشان أخطاءه ما تتداخلش مع فورمات تانية في نفس الصفحة
     */
    protected $errorBag = 'visit';

    protected ?Patient $resolvedPatient = null;

    public function authorize(): bool
    {
        return $this->user()?->doctor !== null;
    }

    protected function prepareForValidation(): void
    {
        /*
        |--------------------------------------------------------------------------
        | تحديد نوع المريض
        |--------------------------------------------------------------------------
        */

        $mode = $this->input('_patient_mode');

        if (! in_array($mode, ['registered', 'external'], true)) {
            $mode = 'registered';
        }

        /*
        |--------------------------------------------------------------------------
        | تنظيف patient_id
        |--------------------------------------------------------------------------
        */

        $patientId = $this->input('patient_id');

        if ($patientId === '') {
            $patientId = null;
        }

        /*
        |--------------------------------------------------------------------------
        | منع اختلاط بيانات التبويبين
        |--------------------------------------------------------------------------
        */

        if ($mode === 'external') {
            $patientId = null;
        }

        $data = [
            '_patient_mode' => $mode,
            'patient_id' => $patientId,
        ];

        /*
        |--------------------------------------------------------------------------
        | تنظيف النصوص
        |--------------------------------------------------------------------------
        */

        foreach (
            [
                'complaint',
                'symptoms',
                'diagnosis',
                'required_tests',
                'required_radiology',
                'notes',
                'patient_name',
                'patient_phone',
            ] as $field
        ) {
            if (
                $this->has($field) &&
                is_string($this->input($field))
            ) {
                $value = trim($this->input($field));

                $data[$field] =
                    $value === ''
                        ? null
                        : $value;
            }
        }

        /*
        |--------------------------------------------------------------------------
        | لو المريض مسجل، لا نحتاج بيانات المريض الخارجي
        |--------------------------------------------------------------------------
        */

        if ($mode === 'registered') {
            $data['patient_name'] = null;
            $data['patient_phone'] = null;
        }

        $this->merge($data);
    }

    public function rules(): array
    {
        return [

            /*
            |--------------------------------------------------------------------------
            | نوع المريض
            |--------------------------------------------------------------------------
            */

            '_patient_mode' => [
                'required',
                'in:registered,external',
            ],

            /*
            |--------------------------------------------------------------------------
            | بيانات المريض المسجل
            |--------------------------------------------------------------------------
            */

            'patient_id' => [
                'nullable',
                'integer',
                'required_if:_patient_mode,registered',
            ],

            /*
            |--------------------------------------------------------------------------
            | بيانات الشخص غير المسجل
            |--------------------------------------------------------------------------
            */

            'patient_name' => [
                'nullable',
                'string',
                'max:150',
                'required_if:_patient_mode,external',
            ],

            /*
            | رقم الهاتف اختياري
            | لكن لو اتكتب لازم يكون رقم مصري صحيح
            */

            'patient_phone' => [
                'nullable',
                'regex:/^01[0125][0-9]{8}$/',
            ],

            /*
            |--------------------------------------------------------------------------
            | موعد المتابعة
            |--------------------------------------------------------------------------
            */
            'next_visit_date'=>[
                'nullable',
                'date',
                'after_or_equal:today',
            ],
            /*
            |--------------------------------------------------------------------------
            | تفاصيل الزيارة
            |--------------------------------------------------------------------------
            */

            'complaint' => [
                'required',
                'string',
                'max:2000',
            ],

            'symptoms' => [
                'nullable',
                'string',
                'max:2000',
            ],

            'diagnosis' => [
                'nullable',
                'string',
                'max:2000',
            ],

            'required_tests' => [
                'nullable',
                'string',
                'max:2000',
            ],

            'required_radiology' => [
                'nullable',
                'string',
                'max:2000',
            ],

            'notes' => [
                'nullable',
                'string',
                'max:3000',
            ],
        ];
    }

    /**
     * التأكد أن المريض المسجل تابع للدكتور الحالي.
     */
    public function after(): array
    {
        return [
            function (Validator $validator) {

                /*
                |--------------------------------------------------------------------------
                | التحقق من المريض المسجل فقط
                |--------------------------------------------------------------------------
                */

                if (
                    $this->input('_patient_mode') !== 'registered'
                ) {
                    return;
                }

                $id = $this->input('patient_id');

                if (
                    blank($id) ||
                    $validator->errors()->has('patient_id')
                ) {
                    return;
                }

                $patient = $this
                    ->user()
                    ->doctor
                    ->patients()
                    ->whereKey($id)
                    ->first();

                if (! $patient) {
                    $validator->errors()->add(
                        'patient_id',
                        'المريض المختار غير موجود ضمن مرضاك.'
                    );

                    return;
                }

                $this->resolvedPatient = $patient;
            },
        ];
    }

    public function patient(): ?Patient
    {
        return $this->resolvedPatient;
    }

    /**
     * البيانات الجاهزة للحفظ.
     *
     * موعد الزيارة يتم تحديده من السيرفر
     * وقت إنشاء الزيارة وليس من الفورم.
     */
    public function payload(): array
    {
        $data = $this->validated();
        $patient = $this->patient();

        return [
            'patient_id' => $patient?->id,

            'patient_name' => $patient
                ? $patient->name
                : ($data['patient_name'] ?? null),

            'patient_phone' => $patient
                ? $patient->phone
                : ($data['patient_phone'] ?? null),

            'visit_date' => now('Africa/Cairo'),

            'complaint' => $data['complaint'] ?? null,

            'symptoms' => $data['symptoms'] ?? null,

            'diagnosis' => $data['diagnosis'] ?? null,

            'required_tests' => $data['required_tests'] ?? null,

            'required_radiology' => $data['required_radiology'] ?? null,

            'notes' => $data['notes'] ?? null,

            'next_visit_date' => $data['next_visit_date'] ?? null,
        ];
    }

